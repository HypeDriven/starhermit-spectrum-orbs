// Writes the native play scripts (tests/native/*.play) from the rules: each
// board's pours come from js/rules.js's solver on the same layout the game
// generates, and the script plays them through the real UI — by keys (→ moves
// the tube focus, Enter lifts and pours), by the numbered tube labels
// (`click =Tube 3`), or by finger on them (`touch =Tube 3` on phones). Each
// pour waits out the 0.42 s resolution that locks input (frames 30). The
// expected totals are js/rules.js's score of the final state.
// tests/native.mjs calls dailyScript() at test time for today's Daily.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const Rules = require('../js/rules.js');
const Content = require('../js/content.js');

const stateOf = (lv) => Rules.createState({ contentId: lv.id, seed: lv.seed, colors: lv.colors, tubeCount: lv.tubeCount, capacity: lv.capacity, stacks: lv.stacks || null, limits: lv.limits || {} });
function solution(lv) {
  const sol = Rules.solve(stateOf(lv), { maxNodes: 400000 });
  if (!sol) throw new Error(`${lv.id} unsolved`);
  return sol;
}
/** Total of a level after `moves` (plus extra invalid / undo counts), as rules.js scores it (no speed par). */
function totalAfter(lv, moves, extra = {}) {
  let s = stateOf(lv);
  for (const m of moves) s = Rules.applyCommand(s, { type: 'move', from: m.from, to: m.to }).state;
  s.invalids += extra.invalids || 0;
  s.undos += extra.undos || 0;
  return Rules.score(s, Object.assign({ timeMs: lv.parTimeMs }, lv.par)).total;
}
/** ui.js showResults's headline for a won round's medal. */
function headline(lv, moves) {
  let s = stateOf(lv);
  for (const m of moves) s = Rules.applyCommand(s, { type: 'move', from: m.from, to: m.to }).state;
  const medal = Rules.score(s, lv.par).medal;
  return { gold: 'A flawless arrangement.', silver: 'Beautifully sorted.', bronze: 'The gallery settles.' }[medal] || 'Sorted — with room to refine.';
}
const STARTED = ['until 300 Medal pace', 'frames 130'];
/** Keys: → (Next tube) to each tube from the current focus, Enter. */
export function byKeys(n, moves, focus = { f: -1 }) {
  const out = [];
  const go = (i) => {
    const steps = focus.f < 0 ? i + 1 : (i - focus.f + n) % n;
    for (let k = 0; k < steps; k++) out.push('key ArrowRight 1', 'frames 2');
    focus.f = i;
    out.push('key Enter 1', 'frames 4');
  };
  for (const m of moves) {
    out.push(`# pour ${m.from + 1} → ${m.to + 1}`);
    go(m.from); go(m.to);
    out.push('frames 30');
  }
  return out;
}
/** The tube labels: a press on one lifts, on another pours. */
export function byLabels(moves, verb = 'click') {
  return moves.flatMap((m) => [`# pour ${m.from + 1} → ${m.to + 1}`, `${verb} =Tube ${m.from + 1}`, 'frames 6', `${verb} =Tube ${m.to + 1}`, 'frames 32']);
}
const header = (what, vp) => [`# Generated by tools/gen-plays.mjs: ${what}`, `# viewport ${vp}`];
const TITLE = ['until 600 Daily Challenge', 'frames 30'];

/** Today's Daily on a desktop, by the tube labels (tests/native.mjs writes it at test time). */
export function dailyScript(date) {
  const lv = Content.dailyForDate(date);
  const sol = solution(lv);
  return [
    `# Generated at test time by tests/native.mjs (tools/gen-plays.mjs dailyScript): ${lv.id}, played by the tube labels.`,
    '# viewport 1440x900@1', ...TITLE,
    'click =Daily Challenge', ...STARTED, 'save daily-board',
    ...byLabels(sol),
    'until 600 Total', `expect ${totalAfter(lv, sol)}`, 'expect Saved to the local board (offline).', 'save daily-results',
  ].join('\n') + '\n';
}

function journey() {
  const J = Content.JOURNEY;
  const s1 = solution(J[0]), s2 = solution(J[1]);
  // stage 2: a mismatched pour first (if the board has one), then the solution with an undo of one extra pour
  const st2 = stateOf(J[1]);
  const acts = Rules.legalActions(st2);
  let bad = null;
  for (let a = 0; a < st2.tubes.length && !bad; a++) for (let b = 0; b < st2.tubes.length && !bad; b++) {
    const why = a !== b && st2.tubes[a].length ? Rules.canMove(st2, a, b).reason : null;
    if (why === 'color-mismatch' || why === 'target-full') bad = { from: a, to: b, why };
  }
  const badText = bad.why === 'color-mismatch' ? 'Colors must match' : 'That tube is full.';
  const extra = acts.find((m) => m.from !== s2[0].from || m.to !== s2[0].to) || acts[0];
  return [...header('Journey stages 1 and 2 on a desktop: stage 1 by keys (→ moves the focus, Enter lifts and pours), stage 2 by the tube labels with an illegal pour, a pour undone and a hint; both to their results.', '1440x900@1'),
    ...TITLE, 'click =Play', 'until 300 Begin', 'frames 10', 'save setup', 'click =Begin', ...STARTED, 'save journey-1',
    ...byKeys(J[0].tubeCount, s1),
    'until 600 Total', `expect ${totalAfter(J[0], s1)}`, `expect ${headline(J[0], s1)}`, 'save journey-1-results',
    'click =Next stage', ...STARTED,
    '# an illegal pour: explained, counted', `click =Tube ${bad.from + 1}`, 'frames 6', `click =Tube ${bad.to + 1}`, 'frames 10',
    `expect ${badText}`, 'save journey-2-invalid', `click =Tube ${bad.from + 1}`, 'frames 200',
    '# a pour, undone', `click =Tube ${extra.from + 1}`, 'frames 6', `click =Tube ${extra.to + 1}`, 'frames 32',
    'click =Undo', 'frames 10',
    'click =Hint', 'frames 20', 'save journey-2-hint',
    ...byLabels(s2),
    'until 600 Total', `expect ${totalAfter(J[1], s2, { invalids: 1, undos: 1 })}`, 'expect Invalid actions × 1', 'expect Undos × 1', 'save journey-2-results',
  ].join('\n') + '\n';
}
